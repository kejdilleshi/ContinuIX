def ensure_devrun():
    """devrun/ with the three symlinks IGM's user-module mechanism needs (see igm-smb-inference-user README §2)."""
    os.makedirs(os.path.join(DEVRUN, "experiment"), exist_ok=True)
    for name, target in (("user", USER_MODULE), ("assimilations", "user/conf/assimilations"),
                         ("data", os.path.join(CX_DIR, "data"))):
        link = os.path.join(DEVRUN, name)
        if not os.path.islink(link):
            os.symlink(target, link)


def env(gpu):
    """Environment of a dev-stack igm_run: dev IGM first on PYTHONPATH, no X, GPU re-indexed to 0."""
    e = dict(os.environ, PYTHONPATH=IGM_DEV, MPLBACKEND="Agg", CUDA_VISIBLE_DEVICES=str(gpu),
             TF_FORCE_GPU_ALLOW_GROWTH="true", TF_CPP_MIN_LOG_LEVEL="3", PYTHONUNBUFFERED="1")
    e.pop("DISPLAY", None)
    return e


