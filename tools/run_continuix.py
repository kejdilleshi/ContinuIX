def run(cmd, dry, env=None, cwd=CX_DIR):
    print("\n$ " + " ".join(str(c) for c in cmd), flush=True)
    if dry:
        return
    full = dict(os.environ, TF_FORCE_GPU_ALLOW_GROWTH="true", TF_CPP_MIN_LOG_LEVEL="3",
                PYTHONUNBUFFERED="1")
    full.update(env or {})
    subprocess.run([str(c) for c in cmd], cwd=cwd, env=full, check=True)


def igm_env(gpu):
    # CUDA_VISIBLE_DEVICES re-indexes the chosen card to 0 (see run_pipeline.pin_gpu)
    return {"CUDA_VISIBLE_DEVICES": str(gpu)}


def load_json(p, default=None):
    if os.path.exists(p):
        with open(p) as f:
            return json.load(f)
    return default


def gpu_free_mib(gpu):
    """Free memory (MiB) of physical GPU `gpu` (other users' jobs share the cards)."""
    try:
        out = subprocess.check_output(["nvidia-smi", "--query-gpu=memory.free", "--format=csv,noheader,nounits",
                                       "-i", str(gpu)], text=True, timeout=30)
        return int(float(out.strip().splitlines()[0]))
    except Exception:
        return 10 ** 9      # cannot query: do not block


def da_mem_mib(meta):
    """GPU memory of one DA-only process (Optuna trial / L-curve run): ~1.7 GB for a few thousand cells,
    ~7.3 GB at 23k cells (S02, measured with another user's job on the card); G01 sizes extrapolated."""
    n = meta["igm_shape"][0] * meta["igm_shape"][1]
    return 2000 if n <= 10000 else 7500 if n <= 40000 else 9000 if n <= 150000 else 12000


def member_mem_mib(meta):
    """GPU memory of one family member (DA + SMB reverse pass), measured in gates G1/G3 with allow_growth:
    ~3 GB for a few thousand cells, ~9 GB at 23k cells (G05/S02), ~17 GB at 129k (G01 100 m), ~24 GB at 227k."""
    n = meta["igm_shape"][0] * meta["igm_shape"][1]
    return 3000 if n <= 10000 else 9500 if n <= 40000 else 17500 if n <= 150000 else 24000


class Ctx:
    def __init__(self, a):
        self.exp, self.gid, self.variant = a.exp, a.gid, a.variant
        self.base = f"{a.exp}_{a.gid}"
        self.name = f"{self.base}_{a.variant}"
        self.src = os.path.join(CX_DIR, "input_data", a.exp, f"{self.base}.nc")
        self.gpr_pair = a.variant in GPR_PAIR
        self.dev = a.variant in DEV_VARIANTS
        self.meta_path = os.path.join(CX_DIR, "data", f"{self.base}{'_dagpr' if self.gpr_pair else '_da' if self.dev else ''}.json")
        self.experiment = f"params_cx_{self.name}"
        self.da_experiment = f"{self.experiment}_da"
        self.results = os.path.join(a.results_root or os.path.join(CX_DIR, "results"), self.name)
        self.state_path = os.path.join(self.results, "state.json")
        self.sweep_dir = os.path.join(self.results, "sweep")
        self.sweep_summary = os.path.join(self.sweep_dir, "sweep_summary.json")
        self.cwd = devstack.DEVRUN if self.dev else CX_DIR            # cwd of every igm_run
        self.exp_dir = os.path.join(self.cwd, "experiment")
        self.reg_key = ("assimilations" if self.dev else "processes") + ".data_assimilation.regularization.thk"
        self.std_key = ("assimilations" if self.dev else "processes") + ".data_assimilation.fitting.thkobs_std"

    def has_gpr(self):
        """GPR thickness observations in the DA (dev stack: decided by tools/gpr_input.py per experiment x glacier)."""
        m = self.meta()
        return self.variant == "gpr" or bool(self.dev and m and m.get("has_gpr"))

    def env(self, gpu):
        return devstack.env(gpu) if self.dev else igm_env(gpu)

    def phys(self, slid, arr):
        """Overrides of the two swept physical parameters (names differ between the stacks)."""
        if self.dev:
            return [f"processes.iceflow.physics.sliding.slidingco={slid}",
                    f"processes.iceflow.physics.sliding.tau_ref={slid * 100.0 ** (1.0 / 3.0)}",
                    f"processes.iceflow.physics.viscosity.arrhenius={arr}"]
        return [f"processes.iceflow.physics.init_slidingco={slid}",
                f"processes.iceflow.physics.init_arrhenius={arr}"]

    def meta(self):
        return load_json(self.meta_path)

    def save(self, st):
        os.makedirs(self.results, exist_ok=True)
        with open(self.state_path, "w") as f:
            json.dump(st, f, indent=2)


