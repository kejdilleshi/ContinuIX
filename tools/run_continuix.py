def stage_convert(a, c, st):
    if c.gpr_pair:
        run([PY, os.path.join(HERE, "gpr_pair_input.py"), c.exp, c.gid], a.dry_run, cwd=CX_DIR)
        return
    if c.dev:          # regular conversion + slope first guess + GPR train/val/test (never a provided THK/BED field)
        run([PY, os.path.join(HERE, "continuix_to_igm.py"), c.src] + (["--dx", str(a.dx)] if a.dx else []),
            a.dry_run, cwd=CX_DIR)
        run([PY, os.path.join(HERE, "gpr_input.py"), c.exp, c.gid], a.dry_run, cwd=CX_DIR)
        return
    run([PY, os.path.join(HERE, "continuix_to_igm.py"), c.src] +
        (["--dx", str(a.dx)] if a.dx else []), a.dry_run, cwd=CX_DIR)


def stage_yaml(a, c, st):
    m = c.meta()
    if m is None:
        print("[yaml] (dry-run) no meta yet"); return
    if c.variant in ("vel", "nogpr"):
        cost = "      - velsurf\n      - icemask"
    else:
        cost = "      - velsurf\n      - thk\n      - icemask"
    common = dict(exp=c.exp, gid=c.gid, variant=c.variant, t1=m["t1"], t2=m["t2"],
                  t_da=m["t_da"], igm_input=m["igm_input"], cost_list=cost,
                  thkobs_std=a.thkobs_std, reg_thk=SWEEP_REG_THK)
    stakes = a.stakes or ""
    if c.dev:
        devstack.ensure_devrun()
        for name, smb in ((c.experiment, True), (c.da_experiment, False)):
            p = os.path.join(c.exp_dir, f"{name}.yaml")
            print(f"[yaml] {'(dry) ' if a.dry_run else ''}write {p}")
            if not a.dry_run:
                with open(p, "w") as f:
                    f.write(devstack.yaml_text(m, c.exp, c.gid, slidingco=0.2, arrhenius=78.0, reg_thk=SWEEP_REG_THK,
                                               thkobs_std=a.thkobs_std, smb=smb, stakes=stakes,
                                               cost=("velsurf", "thk", "icemask") if c.has_gpr() else ("velsurf", "icemask")))
        return
    full = TEMPLATE.format(smb_process="    - smb_inference\n",
                           smb_block=SMB_BLOCK.format(t1=m["t1"], t2=m["t2"], smb_reg=SMB_REG,
                                                      stakes=stakes), **common)
    da = TEMPLATE.format(smb_process="", smb_block="", **common)
    for name, txt in ((c.experiment, full), (c.da_experiment, da)):
        p = os.path.join(CX_DIR, "experiment", f"{name}.yaml")
        print(f"[yaml] {'(dry) ' if a.dry_run else ''}write {p}")
        if not a.dry_run:
            with open(p, "w") as f:
                f.write(txt)


def stage_sweep(a, c, st):
    run([PY, os.path.join(HERE, "sweep_da_dev.py" if c.dev else "sweep_da.py"), "--sweep-dir", c.sweep_dir,
         "--experiment", c.da_experiment,
         "--n-trials", a.n_trials, "--gpus", a.gpus, "--workers-per-gpu", a.workers_per_gpu],
        a.dry_run)
    s = load_json(c.sweep_summary)
    if s is None:
        return
    st["init_slidingco"] = float(s["best_params"]["init_slidingco"])
    st["init_arrhenius"] = float(s["best_params"]["init_arrhenius"])
    st["sweep_best_velsurf"] = float(s["best_velsurf"])
    print(f"[sweep] best: tau_ref={st['init_slidingco']:.4f} A={st['init_arrhenius']:.2f} "
          f"velsurf={st['sweep_best_velsurf']:.3f}")


def stage_lcurve(a, c, st):
    if c.has_gpr():
        return stage_gprtune(a, c, st)
    sweep_dir = os.path.join(c.results, "da_lcurve")
    gpus = [g for g in a.gpus.split(",") if g]
    cmd = ["igm_run", "-m", f"+experiment={c.da_experiment}",
           *c.phys(st['init_slidingco'], st['init_arrhenius']),
           f"{c.reg_key}={a.da_reg}",
           "hydra/launcher=joblib", f"hydra.launcher.n_jobs={a.lcurve_jobs}",
           f"hydra.sweep.dir={sweep_dir}"]
    run(cmd, a.dry_run, env=c.env(gpus[0]), cwd=c.cwd)
    run([PY, os.path.join(HERE, "analyze_lcurve_dev.py") if c.dev
         else os.path.join(IGM_CODE, "pipeline", "analyze_da_lcurve.py"), sweep_dir,
         "--input", os.path.join("data", c.meta()["igm_input"]) if c.meta() else "?"], a.dry_run)
    res = load_json(os.path.join(sweep_dir, "da_lcurve_result.json"))
    if res:
        st["reg_thk"] = float(res["best_reg"])
        print(f"[lcurve] corner reg.thk={st['reg_thk']:g}")


def stage_gprtune(a, c, st):
    """GPR available: DA grid over (reg.thk, thkobs_std) at the best (tau_ref, A); pick on the validation GPR."""
    sweep_dir = os.path.join(c.results, "gpr_tune")
    gpus = [g for g in a.gpus.split(",") if g]
    cmd = ["igm_run", "-m", f"+experiment={c.da_experiment}",
           *c.phys(st['init_slidingco'], st['init_arrhenius']),
           f"{c.reg_key}={GPR_REG_GRID}",
           f"{c.std_key}={GPR_STD_GRID}",
           "hydra/launcher=joblib", f"hydra.launcher.n_jobs={a.lcurve_jobs}",
           f"hydra.sweep.dir={sweep_dir}"]
    run(cmd, a.dry_run, env=c.env(gpus[0]), cwd=c.cwd)
    run([PY, os.path.join(HERE, "gpr_eval.py"), "tune", sweep_dir, "--input", c.meta()["igm_input"],
         "--tol", str(GPR_TOL)], a.dry_run)
    res = load_json(os.path.join(sweep_dir, "gpr_tune_result.json"))
    if res:
        st["reg_thk"], st["thkobs_std"] = float(res["best"]["reg_thk"]), float(res["best"]["thkobs_std"])
        print(f"[gprtune] reg.thk={st['reg_thk']:g} thkobs_std={st['thkobs_std']:g} "
              f"(val RMSE {res['best']['val_rmse']:.1f} m)")


def select_family(c):
    """tau_ref values from the sweep: velsurf <= cutoff*best, thinned in log space."""
    rows = [r for r in load_json(c.sweep_summary)["results"] if math.isfinite(r["velsurf"])]
    rows.sort(key=lambda r: r["velsurf"])
    best = rows[0]["velsurf"]
    kept = []
    for r in rows:
        if r["velsurf"] > best * FAMILY_CUTOFF:
            break
        v = r["init_slidingco"]
        if all(max(v, k) / min(v, k) >= FAMILY_THIN for k in kept):
            kept.append(v)
        if len(kept) >= FAMILY_MAX:
            break
    return sorted(kept)


def family_cmd(c, st, slid, out_dir):
    return ["igm_run", f"+experiment={c.experiment}", *c.phys(slid, st['init_arrhenius']),
            f"{c.reg_key}={st['reg_thk']}"] + \
           ([f"{c.std_key}={st['thkobs_std']}"] if "thkobs_std" in st else []) + \
           [f"hydra.run.dir={out_dir}"]


def stage_family(a, c, st):
    slids = [float(x) for x in a.slidingco.split(",")] if a.slidingco else select_family(c)
    st["family_slidingco"] = slids
    gpus = [g for g in a.gpus.split(",") if g]
    print(f"[family] tau_ref = {', '.join(f'{s:.4f}' for s in slids)} on GPUs {gpus}")
    # members run in waves of len(gpus) * family_parallel (default 1 per GPU, see igm-on-octopus; the
    # runs are CPU/latency-bound, so several per GPU are possible when the memory fits)
    slots = gpus * max(1, int(a.family_parallel))
    need = member_mem_mib(c.meta()) if c.meta() else 0
    pending = list(slids)
    while pending:
        # wave size = what fits in the free memory of the lane's GPU right now (waits if not even one fits)
        k = len(slots)
        while not a.dry_run and need:
            k = min(len(slots), gpu_free_mib(gpus[0]) // need)
            if k >= 1:
                break
            print(f"[family] waiting for GPU memory: need {need} MiB, free {gpu_free_mib(gpus[0])} MiB", flush=True)
            time.sleep(300)
        wave, pending = pending[:k], pending[k:]
        procs = []
        for slid, gpu in zip(wave, slots):
            out_dir = os.path.join(c.results, "family", f"slid_{slid:.4f}")
            cmd = family_cmd(c, st, slid, out_dir)
            print("\n$ " + " ".join(cmd), flush=True)
            if a.dry_run:
                continue
            os.makedirs(out_dir, exist_ok=True)
            env = dict(os.environ, TF_FORCE_GPU_ALLOW_GROWTH="true", TF_CPP_MIN_LOG_LEVEL="3", PYTHONUNBUFFERED="1")
            env.update(c.env(gpu))      # the dev-stack env is a full environment that repeats these keys
            log = open(out_dir + ".log", "w")
            procs.append((slid, subprocess.Popen(cmd, cwd=c.cwd, env=env,
                                                 stdout=log, stderr=subprocess.STDOUT)))
        for slid, p in procs:
            try:
                rc = p.wait(timeout=a.member_timeout_h * 3600)
            except subprocess.TimeoutExpired:
                p.kill(); rc = -9
                print(f"[family] tau_ref={slid:.4f} killed after {a.member_timeout_h} h without finishing", flush=True)
            print(f"[family] tau_ref={slid:.4f} exit {rc}")
            if rc != 0:
                raise SystemExit(f"family run tau_ref={slid} failed; see its .log")


def stage_export(a, c, st):
    thk_sigma = []
    if c.gpr_pair or c.has_gpr():   # held-out GPR scores of every family member (test set: reported, never used for a choice)
        run([PY, os.path.join(HERE, "gpr_eval.py"), "family", os.path.join(c.results, "family"),
             "--input", c.meta()["igm_input"]], a.dry_run)
        sc = load_json(os.path.join(c.results, "gpr_scores.json"))
        if c.dev and sc and math.isfinite(sc["member_mean"].get("val_rmse", float("nan"))):
            thk_sigma = ["--thk-sigma", f"{sc['member_mean']['val_rmse']:.2f}", "--thk-sigma-source",
                         "RMSE of the family-mean DA thickness on the validation GPR profiles"]
    run([PY, os.path.join(HERE, "igm_to_continuix.py"), "--run-root", c.results,
         "--meta", c.meta_path, "--method", a.method,
         "--out-dir", a.export_dir or (os.path.join(CX_DIR, "results", "gpr_pair_export", c.exp) if c.gpr_pair
                                       else os.path.join(CX_DIR, "GROUP_UNIL", c.exp))] + thk_sigma, a.dry_run)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--exp", required=True)
    ap.add_argument("--gid", required=True)
    ap.add_argument("--variant", choices=["cnn", "vel", "velthk", "nogpr", "gpr"], default="cnn")
    ap.add_argument("--method", default=None, help="method number for file names (default vel=01, velthk=02)")
    ap.add_argument("--from-stage", choices=STAGES, default="convert")
    ap.add_argument("--to-stage", choices=STAGES, default="export")
    ap.add_argument("--dx", type=float, default=None)
    ap.add_argument("--gpus", default="0,1")
    ap.add_argument("--n-trials", default="30")
    ap.add_argument("--workers-per-gpu", default="1")
    ap.add_argument("--member-timeout-h", type=float, default=12.0, help="kill a family member that runs longer than this")
    ap.add_argument("--family-parallel", type=int, default=1, help="family members run concurrently per GPU")
    ap.add_argument("--da-reg", default=DA_REG_GRID)
    ap.add_argument("--lcurve-jobs", default="3", help="parallel DA runs on the L-curve GPU")
    ap.add_argument("--thkobs-std", type=float, default=20.0)
    ap.add_argument("--slidingco", default=None, help="comma list: skip family selection")
    ap.add_argument("--init-slidingco", type=float, default=None)
    ap.add_argument("--init-arrhenius", type=float, default=None)
    ap.add_argument("--reg-thk", type=float, default=None)
    ap.add_argument("--results-root", default=None, help="dev/gate runs: results go to <root>/<EXP>_<GID>_<variant> (default results/)")
    ap.add_argument("--export-dir", default=None, help="dev/gate runs: write the exported .nc here instead of GROUP_UNIL/<EXP>")
    ap.add_argument("--stakes", default=None,
                    help="stake CSV for the diagnostic overlay only (never enters the cost)")
    ap.add_argument("--resume", action="store_true", help="skip stages already recorded as done")
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()
    a.method = a.method or {"cnn": "01", "vel": "01", "velthk": "02", "nogpr": "03", "gpr": "04"}[a.variant]

    c = Ctx(a)
    st = load_json(c.state_path, {}) or {}
    for k, v in (("init_slidingco", a.init_slidingco), ("init_arrhenius", a.init_arrhenius),
                 ("reg_thk", a.reg_thk)):
        if v is not None:
            st[k] = v
    todo = STAGES[STAGES.index(a.from_stage): STAGES.index(a.to_stage) + 1]
    done = st.setdefault("done_stages", [])
    if a.resume:
        todo = [s for s in todo if s not in done]
    print(f"=== ContinuIX {c.name}: stages {todo} ===")
    for s in todo:
        globals()[f"stage_{s}"](a, c, st)
        if not a.dry_run:
            if s not in done:
                done.append(s)
            c.save(st)
    print(json.dumps(st, indent=2))


if __name__ == "__main__":
    main()
