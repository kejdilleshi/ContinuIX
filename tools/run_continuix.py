#!/usr/bin/env python3
"""
Run the igm-smb-inference method (Lleshi et al.) on one ContinuIX glacier.

Everything (inputs, configs, sweeps, runs, outputs) lives in ContinuIX/; only the
code is taken from igm-smb-inference (user/ symlink + pipeline scripts).

Stages (each resumable; state in results/<EXP>_<GID>_<variant>/state.json):

  convert  ContinuIX NetCDF -> IGM input (tools/continuix_to_igm.py)
  yaml     write ContinuIX/experiment/params_cx_<EXP>_<GID>_<variant>{,_da}.yaml
  sweep    Optuna TPE over (init_slidingco = tau_ref, init_arrhenius = A) on the
           DA surface-velocity misfit (optuna_sweep_da_nsga.py, unchanged)
  lcurve   DA reg.thk L-curve at the best (tau_ref, A), corner auto-picked
           (pipeline/analyze_da_lcurve.py, unchanged)
  family   combined DA + SMB-inference runs for the low-misfit tau_ref family
           (velsurf <= 1.5 x best, thinned in log space, <= 5 values) at the
           best A and the L-curve reg.thk — the paper's Sect. 3.3 procedure
  export   family -> EXP##_G##_method##.nc on the native ContinuIX grid
           (tools/igm_to_continuix.py)

Variants
  vel     the published method: DA cost = [velsurf, icemask]; the provided
          thickness is only the DA initial guess (as in the paper's Argentiere run)
  velthk  thickness-aware DA: cost = [velsurf, thk, icemask], provided
          thickness as thkobs with its stated uncertainty (default 20 m)
  nogpr   with/without-GPR comparison (tools/gpr_pair_input.py): no provided THK/BED anywhere, DA first
          guess from the surface slope, cost = [velsurf, icemask]
  gpr     same first guess, cost = [velsurf, thk, icemask] with the TRAIN GPR profiles as thkobs; the
          lcurve stage becomes a (reg.thk x thkobs_std) grid picked on the VALIDATION profiles
          (the least-constrained setting within 5 % of the best validation RMSE: no overfitting)
  cnn     THE CURRENT METHOD (method01, since 2026-10-13). Dev stack (tools/devstack.py): IGM dev + the
          igm-smb-inference-user module + the CNN bundled with IGM (pinnbp_10_4_cnn_16_32_2_1_a). No provided
          THK/BED field anywhere (tools/gpr_input.py): DA first guess from the surface slope; GPR profiles, where
          the glacier has them (G02, G03, G05, S02; not EXP17-20), enter the DA as thkobs on TRAIN profiles, and the
          lcurve stage becomes the (reg.thk x thkobs_std) grid picked on VALIDATION profiles (gprtune, least-
          constrained setting within 5 % of the best); TEST profiles are only reported. Without GPR: velocity-only
          DA and the reg.thk L-curve. Runs in devrun/, exported to GROUP_UNIL/<EXP>.

Usage
  conda activate igm-pretrain
  python tools/run_continuix.py --exp EXP01 --gid G03 --variant vel
  python tools/run_continuix.py --exp EXP01 --gid G03 --variant vel --from-stage family
  python tools/run_continuix.py --exp EXP01 --gid G03 --dry-run
"""
