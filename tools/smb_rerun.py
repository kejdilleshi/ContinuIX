#!/usr/bin/env python3
"""
Rerun ONLY the SMB-inference phase of finished `cnn` family members, on their saved DA result.

Each member of results/<EXP>_<GID>_cnn/family/slid_* holds the DA geometry (geology-optimized.nc).
Here IGM runs with assimilations = [da_restore, smb_inference] in smbrun/ (a ContinuIX copy of the
igm-smb-inference-user module, where the SMB-phase changes live): da_restore puts the DA thickness /
bed back on the state, smb_inference runs with the settings given by --set. The emulator is the frozen
pretrained one in the DA and here alike, so with the original settings the original SMB phase is
reproduced exactly.

Outputs: results/<EXP>_<GID>_cnn/smb_<tag>/slid_*/ (smb_inference/ outputs, plus symlinks to the
member's geology-optimized.nc and costs.dat, so tools/igm_to_continuix.py --members reads them as is).

  python tools/smb_rerun.py --exp EXP01 --gid S01 --tag base
  python tools/smb_rerun.py --exp EXP01 --gid S01 --tag dz50 --set inversion.dz=50 optimization.regularisation=0.001
  python tools/smb_rerun.py --exp EXP01 --gid S01 --tag dz50 --export      # + export to smb_<tag>/export/
"""
import argparse
import glob
import json
import os
import subprocess
import sys
import time

import yaml

os.environ["MPLBACKEND"] = "Agg"          # see run_continuix.py: never let a detached run probe X
os.environ.pop("DISPLAY", None)
HERE = os.path.dirname(os.path.abspath(__file__))
CX_DIR = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import devstack  # noqa: E402

SMBRUN = os.path.join(CX_DIR, "smbrun")
PY = sys.executable

