def members_of(exp, gid, which, fam=None):
    fam = os.path.abspath(fam) if fam else os.path.join(CX_DIR, "results", f"{exp}_{gid}_cnn", "family")
    dirs = sorted(d for d in glob.glob(os.path.join(fam, "slid_*")) if os.path.isdir(d))
    if which:
        keep = set(which.split(","))
        dirs = [d for d in dirs if os.path.basename(d) in keep or os.path.basename(d)[5:] in keep]
    return dirs


def physics_overrides(member):
    """The member's own iceflow overrides (slidingco, tau_ref, arrhenius), verbatim from its hydra record."""
    with open(os.path.join(member, ".hydra", "overrides.yaml")) as f:
        ov = yaml.safe_load(f)
    return [o for o in ov if o.startswith("processes.iceflow.")]


def write_yaml(exp, gid, meta):
    os.makedirs(os.path.join(SMBRUN, "experiment"), exist_ok=True)
    name = f"params_smb_{exp}_{gid}"
    with open(os.path.join(SMBRUN, "experiment", f"{name}.yaml"), "w") as f:
        f.write(TEMPLATE.format(exp=exp, gid=gid, t1=meta["t1"], t2=meta["t2"], t_da=meta["t_da"],
                                igm_input=meta["igm_input"]))
    return name


def launch(member, out_dir, experiment, sets, gpu):
    os.makedirs(out_dir, exist_ok=True)
    for fn in ("geology-optimized.nc", "costs.dat"):
        link = os.path.join(out_dir, fn)
        if not os.path.lexists(link):
            os.symlink(os.path.join(member, fn), link)
    cmd = ["igm_run", f"+experiment={experiment}", *physics_overrides(member),
           f"assimilations.da_restore.file={os.path.join(member, 'geology-optimized.nc')}",
           *[f"assimilations.smb_inference.{s.replace('{member}', os.path.basename(member))}" for s in sets], f"hydra.run.dir={out_dir}"]
    env = devstack.env(gpu)
    log = open(out_dir + ".log", "w")
    log.write("$ " + " ".join(cmd) + "\n"); log.flush()
    return subprocess.Popen(cmd, cwd=SMBRUN, env=env, stdout=log, stderr=subprocess.STDOUT)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--exp", required=True)
    ap.add_argument("--gid", required=True)
    ap.add_argument("--tag", required=True, help="output folder results/<EXP>_<GID>_cnn/smb_<tag>/")
    ap.add_argument("--members", default=None, help="comma list of slid_* names or tau values (default: all)")
    ap.add_argument("--set", nargs="*", default=[], help="smb_inference overrides, e.g. inversion.dz=50; "
                    "{member} expands to the member's slid_* name")
    ap.add_argument("--gpus", default="0,1")
    ap.add_argument("--jobs", type=int, default=5, help="members run concurrently")
    ap.add_argument("--export", action="store_true", help="export the rerun family to smb_<tag>/export/")
    ap.add_argument("--export-dir", default=None)
    ap.add_argument("--method", default="01")
    ap.add_argument("--family-dir", default=None, help="DA runs to restore (default results/<EXP>_<GID>_cnn/family)")
    ap.add_argument("--meta", default=None, help="input meta json (default data/<EXP>_<GID>_da.json)")
    a = ap.parse_args()

    meta_path = os.path.abspath(a.meta) if a.meta else os.path.join(CX_DIR, "data", f"{a.exp}_{a.gid}_da.json")
    meta = json.load(open(meta_path))
    root = os.path.join(CX_DIR, "results", f"{a.exp}_{a.gid}_cnn", f"smb_{a.tag}")
    os.makedirs(root, exist_ok=True)
    with open(os.path.join(root, "settings.json"), "w") as f:
        json.dump({"set": a.set, "members": a.members, "time": time.strftime("%Y-%m-%d %H:%M:%S")}, f, indent=2)
    experiment = write_yaml(a.exp, a.gid, meta) if not a.meta else write_yaml(a.exp, a.gid + "_" + os.path.basename(a.meta)[:-5], meta)
    members = members_of(a.exp, a.gid, a.members, a.family_dir)
    gpus = [g for g in a.gpus.split(",") if g]
    print(f"[smb_rerun] {a.exp} {a.gid} tag={a.tag}: {len(members)} members, set={a.set}", flush=True)

    pending, running, failed, k = list(members), [], [], 0
    while pending or running:
        while pending and len(running) < a.jobs:
            m = pending.pop(0)
            out = os.path.join(root, os.path.basename(m))
            running.append((m, launch(m, out, experiment, a.set, gpus[k % len(gpus)])))
            k += 1
        time.sleep(5)
        for m, p in list(running):
            if p.poll() is not None:
                running.remove((m, p))
                print(f"[smb_rerun] {os.path.basename(m)} exit {p.returncode}", flush=True)
                if p.returncode != 0:
                    failed.append(m)
    if failed:
        raise SystemExit(f"[smb_rerun] failed: {failed}")

    if a.export:
        outs = [os.path.join(root, os.path.basename(m)) for m in members]
        subprocess.run([PY, os.path.join(HERE, "igm_to_continuix.py"), "--run-root", root, "--meta", meta_path,
                        "--method", a.method, "--out-dir", a.export_dir or os.path.join(root, "export"),
                        "--plot-dir", root, "--members", *outs], check=True, cwd=CX_DIR)


if __name__ == "__main__":
    main()
